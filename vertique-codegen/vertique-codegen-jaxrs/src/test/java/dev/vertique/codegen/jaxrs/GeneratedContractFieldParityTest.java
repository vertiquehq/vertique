    // --- @ValidateWith ---

    interface Create {}

    interface ValidatedApi {
        @POST
        @Path("/overridden")
        @ValidateWith({Create.class})
        String overridden(String body);

        @POST
        @Path("/inherited")
        @ValidateWith({Create.class})
        String inherited(String body);
    }

    @Path("/validated")
    static class ValidatedResource implements ValidatedApi {
        @Override
        @ValidateWith({})
        public String overridden(String body) {
            return body;
        }

        @Override
        public String inherited(String body) {
            return body;
        }
    }

    private static List<String> groupNames(ResourceMethodMeta meta) {
        return meta.validationGroups() == null
                ? null
                : Arrays.stream(meta.validationGroups()).map(Class::getName).toList();
    }

    @Test
    @DisplayName(
            "an explicit empty @ValidateWith on an override wins over the interface groups like the reflective scan")
    void emptyValidateWithOverride() throws Exception {
        Scans scans = scan(
                new ValidatedResource(),
                "ValidatedResource",
                src("Create", "public interface Create {}\n"),
                src("ValidatedApi", """
                        public interface ValidatedApi {
                            @POST
                            @Path("/overridden")
                            @ValidateWith({Create.class})
                            String overridden(String body);

                            @POST
                            @Path("/inherited")
                            @ValidateWith({Create.class})
                            String inherited(String body);
                        }
                        """),
                src("ValidatedResource", """
                        @Path("/validated")
                        public class ValidatedResource implements ValidatedApi {
                            @Override
                            @ValidateWith({})
                            public String overridden(String body) {
                                return body;
                            }

                            @Override
                            public String inherited(String body) {
                                return body;
                            }
                        }
                        """));
        assertEquals(List.of(), groupNames(pick(scans.reflective(), "overridden")));
        assertEquals(1, groupNames(pick(scans.reflective(), "inherited")).size());
        assertEquals(
                groupNames(pick(scans.reflective(), "overridden")), groupNames(pick(scans.generated(), "overridden")));
        assertEquals(1, groupNames(pick(scans.generated(), "inherited")).size());
    }

    // --- @DefaultValue on sources that do not take one ---

    public static class SearchBean {
        @QueryParam("page")
        public String page;
    }

    @Path("/defaults")
    static class DefaultsResource {
        @POST
        @Path("/body")
        public String body(@DefaultValue("x") String body) {
            return body;
        }

        @GET
        @Path("/bean")
        public String bean(@BeanParam @DefaultValue("x") SearchBean bean) {
            return "bean";
        }

        @GET
        @Path("/context")
        public String context(@Context @DefaultValue("x") RoutingContext routingContext) {
            return "context";
        }

        @POST
        @Path("/files")
        public String files(@DefaultValue("x") List<FileUpload> files) {
            return "files";
        }

        @GET
        @Path("/query")
        public String query(@QueryParam("q") @DefaultValue("x") String q) {
            return q;
        }
    }

    @Test
    @DisplayName("@DefaultValue is dropped for body, bean, context and file parameters like the reflective scan")
    void defaultValueOnNonScalarSources() throws Exception {
        Scans scans =
                scan(new DefaultsResource(), "DefaultsResource", src("SearchBean", """
                public class SearchBean {
                    @QueryParam("page")
                    public String page;
                }
                """), src("DefaultsResource", """
                @Path("/defaults")
                public class DefaultsResource {
                    @POST
                    @Path("/body")
                    public String body(@DefaultValue("x") String body) {
                        return body;
                    }

                    @GET
                    @Path("/bean")
                    public String bean(@BeanParam @DefaultValue("x") SearchBean bean) {
                        return "bean";
                    }

                    @GET
                    @Path("/context")
                    public String context(@Context @DefaultValue("x") RoutingContext routingContext) {
                        return "context";
                    }

                    @POST
                    @Path("/files")
                    public String files(@DefaultValue("x") List<FileUpload> files) {
                        return "files";
                    }

                    @GET
                    @Path("/query")
                    public String query(@QueryParam("q") @DefaultValue("x") String q) {
                        return q;
                    }
                }
                """));
        for (String method : List.of("body", "bean", "context", "files")) {
            var reflective = pick(scans.reflective(), method).params().get(0);
            var generated = pick(scans.generated(), method).params().get(0);
            assertEquals(null, reflective.defaultValue(), "reflective default of " + method);
            assertEquals(reflective.source(), generated.source(), "source of " + method);
            assertEquals(reflective.defaultValue(), generated.defaultValue(), "default of " + method);
        }
        // A scalar source keeps its default on both engines.
        assertEquals("x", pick(scans.reflective(), "query").params().get(0).defaultValue());
        assertEquals("x", pick(scans.generated(), "query").params().get(0).defaultValue());
    }

    // --- Operation identifier per attribute ---

    interface ItemsApi {
        @GET
        @Path("/items")
        @Operation(operationId = "listItems")
        String list();

        @GET
        @Path("/blank")
        @Operation(operationId = "fromInterface")
        String blank();

        @GET
        @Path("/own")
        @Operation(operationId = "inherited")
        String own();
    }

    @Path("/api")
    static class ItemsResource implements ItemsApi {
        @Override
        @Operation(summary = "x")
        public String list() {
            return "list";
        }

        @Override
        @Operation(operationId = " ")
        public String blank() {
            return "blank";
        }

        @Override
        @Operation(operationId = "own")
        public String own() {
            return "own";
        }
    }

    @Test
    @DisplayName("an override's @Operation without an id takes the overridden declaration's id in both engines")
    void operationIdPerAttribute() throws Exception {
        Scans scans = scan(new ItemsResource(), "ItemsResource", src("ItemsApi", """
                public interface ItemsApi {
                    @GET
                    @Path("/items")
                    @Operation(operationId = "listItems")
                    String list();

                    @GET
                    @Path("/blank")
                    @Operation(operationId = "fromInterface")
                    String blank();

                    @GET
                    @Path("/own")
                    @Operation(operationId = "inherited")
                    String own();
                }
                """), src("ItemsResource", """
                @Path("/api")
                public class ItemsResource implements ItemsApi {
                    @Override
                    @Operation(summary = "x")
                    public String list() {
                        return "list";
                    }

                    @Override
                    @Operation(operationId = " ")
                    public String blank() {
                        return "blank";
                    }

                    @Override
                    @Operation(operationId = "own")
                    public String own() {
                        return "own";
                    }
                }
                """));
        assertEquals("listItems", pick(scans.generated(), "list").operationId());
        assertEquals("fromInterface", pick(scans.generated(), "blank").operationId());
        assertEquals("own", pick(scans.generated(), "own").operationId());
        for (String method : List.of("list", "blank", "own")) {
            assertEquals(
                    pick(scans.generated(), method).operationId(),
                    pick(scans.reflective(), method).operationId(),
                    "operation id of " + method);
        }
    }
