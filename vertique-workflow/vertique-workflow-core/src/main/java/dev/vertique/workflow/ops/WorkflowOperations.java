package dev.vertique.workflow.ops;

import io.vertx.core.Future;

/**
 * Public, SQL-free facade for interacting with workflow instances.
 *
 * <p>All methods are asynchronous and return {@link Future}. Implementations must not block the
 * Vert.x event loop.
 *
 * <p>The concrete implementation (in {@code vertique-workflow-postgresql}) opens and manages its
 * own database transaction per call. Callers that need to participate in an existing transaction
 * should use {@code TransactionalWorkflowOperations} instead.
 */
public interface WorkflowOperations {

    /**
     * Starts a new workflow instance for the given command.
     *
     * <p>If a workflow instance with the same {@code idempotencyKey} within the definition scope
     * already exists, the existing instance id is returned without creating a duplicate (idempotent
     * start).
     *
     * @param cmd command describing the definition, payload, and idempotency key
     * @return a {@link Future} that resolves to the id of the created (or existing) workflow
     *     instance
     */
    Future<WorkflowInstanceId> start(StartCommand cmd);

    /**
     * Delivers an external signal to a workflow instance by recording it.
     *
     * <p>The call returns once the signal is recorded as a command of the instance; an executor applies it
     * afterwards, in the order the instance's commands were recorded. A signal the instance does not await yet is
     * parked and applied when the instance reaches a wait that accepts it. The call is refused only for a missing or
     * ended instance, a name the instance's pinned definition does not declare for the addressed wait, a payload over
     * the record-time size or depth bounds, or an instance that already holds the configured number of open signals.
     * The {@code signalDedupKey} prevents duplicate signal delivery: a repeated key returns success and records
     * nothing.
     *
     * @param id id of the workflow instance to signal
     * @param signalName name of the signal to deliver
     * @param payload signal payload; bound to the declared payload type when the signal is applied
     * @param signalDedupKey caller-supplied dedup key; no random fallback
     * @return a {@link Future} that completes when the signal has been recorded, not when it has been applied
     */
    Future<Void> signal(WorkflowInstanceId id, String signalName, Object payload, String signalDedupKey);

    /**
     * Delivers an external signal on behalf of a client of the named contract.
     *
     * <p>A binding that checks contracts compares {@code contractName} with the contract of the
     * definition version the instance is pinned to and refuses the signal, changing nothing, when they
     * differ. The default implementation performs no check and delegates to
     * {@link #signal(WorkflowInstanceId, String, Object, String)}.
     *
     * <p>A wrapper or decorator around another binding must override this method and forward it to the
     * wrapped binding; inheriting the default silently drops the caller-contract check. The check is a
     * guard against developer error, such as a client built for the wrong contract; it is not an
     * authorization boundary, because the contract name is supplied by the caller. A client proxy
     * generated by an older annotation processor does not call this overload and fails with a
     * {@link dev.vertique.workflow.exception.WorkflowClientProxyLinkageException} until it is rebuilt.
     *
     * @param id id of the workflow instance to signal
     * @param contractName logical name of the contract of the client that sends the signal
     * @param signalName name of the signal to deliver
     * @param payload signal payload; coerced to the declared payload type if necessary
     * @param signalDedupKey caller-supplied dedup key; no random fallback
     * @return a {@link Future} that completes when the signal has been recorded; it fails with a
     *     {@link dev.vertique.workflow.exception.WorkflowDefinitionContractMismatchException} when a
     *     contract-checking binding finds the instance pinned to a definition of another contract
     */
    default Future<Void> signal(
            WorkflowInstanceId id, String contractName, String signalName, Object payload, String signalDedupKey) {
        return signal(id, signalName, payload, signalDedupKey);
    }

    /**
     * Cancels a workflow instance that has not ended: one that is pending, running, waiting, compensating or failed.
     * The call is synchronous and records no command. Under the instance's execution lock, which it waits for, it
     * cancels every pending, deferred, claimed, parked and dead-lettered command of the instance, the timers they fire
     * and the open and reserved tasks, cancels the active branches and marks the instance {@code CANCELLED}. An
     * instance cancelled before its start ran keeps no state and no current step. An instance that has ended is
     * refused.
     *
     * @param id id of the workflow instance to cancel
     * @param reason human-readable reason for the cancellation; stored in history
     * @return a {@link Future} that completes when the instance has been transitioned to
     *     {@code CANCELLED}
     */
    Future<Void> cancel(WorkflowInstanceId id, String reason);

    /**
     * Records a retry of a workflow instance: the single recovery operation. The call returns once the retry is
     * recorded; an executor carries it out afterwards, in queue order (await the execution probe to observe the
     * effect).
     *
     * <p>When it runs, the retry:
     * <ul>
     *   <li>initializes an instance whose start failed before initialization from the stored start payload, and
     *       settles a dead-lettered start as superseded;</li>
     *   <li>drives a {@code FAILED} instance again from its current step and applies the signals parked meanwhile at the
     *       wait it reaches;</li>
     *   <li>then offers every dead-lettered command of the instance again with its attempts reset, keeping their order,
     *       so that they run next; if the drive ended the instance they are rejected instead.</li>
     * </ul>
     * A retry that finds nothing left to recover completes as stale, and a retry whose drive fails again leaves the
     * instance {@code FAILED}.
     *
     * @param id id of the workflow instance to recover; it must be {@code FAILED} or hold a dead-lettered command
     * @return a {@link Future} that completes when the retry is recorded; it fails with
     *     {@link dev.vertique.workflow.exception.WorkflowSignalRejectedException} naming the instance and its status
     *     when the instance has ended or is neither {@code FAILED} nor holds a dead-lettered command, and
     *     records nothing then
     */
    Future<Void> retry(WorkflowInstanceId id);

    /**
     * Returns a read-only view of the workflow instance and its recent history.
     *
     * <p>This is a read-only operation and does not require a write transaction. It succeeds even
     * if the workflow definition version is no longer registered, because it reads no plan.
     *
     * @param id id of the workflow instance to query
     * @return a {@link Future} that resolves to a {@link WorkflowView} containing the instance
     *     snapshot and recent history
     */
    Future<WorkflowView> query(WorkflowInstanceId id);

    /**
     * Returns a read-only view of the workflow instance on behalf of a client of the named contract.
     *
     * <p>A binding that checks contracts compares {@code contractName} with the contract of the
     * definition version the instance is pinned to and refuses the query when they differ. Unlike
     * {@link #query(WorkflowInstanceId)}, which needs no plan, the check needs the pinned plan: a binding
     * that holds no code for that version fails with
     * {@link dev.vertique.workflow.exception.WorkflowVersionNotRunnableException}. The default implementation
     * performs no check and delegates to {@link #query(WorkflowInstanceId)}.
     *
     * <p>A wrapper or decorator around another binding must override this method and forward it to the
     * wrapped binding; inheriting the default silently drops the caller-contract check. The check is a
     * guard against developer error, such as a client built for the wrong contract; it is not an
     * authorization boundary, because the contract name is supplied by the caller. A client proxy
     * generated by an older annotation processor does not call this overload and fails with a
     * {@link dev.vertique.workflow.exception.WorkflowClientProxyLinkageException} until it is rebuilt.
     *
     * @param id id of the workflow instance to query
     * @param contractName logical name of the contract of the client that sends the query
     * @return a {@link Future} that resolves to a {@link WorkflowView}; it fails with a
     *     {@link dev.vertique.workflow.exception.WorkflowDefinitionContractMismatchException} when a
     *     contract-checking binding finds the instance pinned to a definition of another contract
     */
    default Future<WorkflowView> query(WorkflowInstanceId id, String contractName) {
        return query(id);
    }

    /**
     * Records the migration of a workflow instance from its current definition version to {@code targetVersion} using an
     * application-registered {@link dev.vertique.workflow.migration.WorkflowMigrationHandler}. The call returns once the
     * migration is recorded; an executor that holds both the source and the target plan carries it out afterwards, in
     * queue order (await the execution probe to observe the effect), and a node that holds either plan not leaves it
     * for one that does.
     *
     * <p>The executor rejects the migration, leaving the instance on its previous version, state and status, and
     * records the rejection in the instance's history and the command's last error, when:
     * <ul>
     *   <li>the instance has failed or has active fork-branch state;</li>
     *   <li>no handler matches {@code (definitionId, currentVersion, targetVersion)} within the instance's definition
     *       scope, or the handler's source or target state type is not the state type of the corresponding
     *       definition;</li>
     *   <li>the target version is deprecated, marked failing, of another contract, or not admitted for a new pin;</li>
     *   <li>the handler or the re-pin fails, or the target plan's drive overruns the step cap of a segment.</li>
     * </ul>
     * When it is applied, a {@code WORKFLOW_MIGRATED} history entry is appended, and the parked signals the target
     * version does not declare are rejected.
     *
     * <p>This default implementation throws {@link UnsupportedOperationException}. The real
     * implementation lives in {@code vertique-workflow-postgresql} and requires
     * {@code WorkflowMigrationModule} to be installed in the Dagger component.
     *
     * @param id workflow instance to migrate
     * @param targetVersion the definition version to migrate to
     * @return a {@link Future} that completes when the migration is recorded; it fails with
     *     {@link dev.vertique.workflow.migration.WorkflowMigrationIllegalStateException} naming the status when the
     *     instance has ended, and records nothing then
     */
    default Future<Void> migrate(WorkflowInstanceId id, long targetVersion) {
        return Future.failedFuture(
                new UnsupportedOperationException("migrate() is not implemented by this WorkflowOperations binding;"
                        + " install vertique-workflow-postgresql + WorkflowMigrationModule"
                        + " (or another binding that implements migrate)"));
    }

    /**
     * Records the migration of a workflow instance to {@code targetVersion} of the definition of the same id in
     * {@code targetScope}.
     *
     * <p>The rules of {@link #migrate(WorkflowInstanceId, long)} apply, with these differences: the target
     * definition is the one of {@code targetScope}, which must be the instance's start scope or the default scope;
     * it must name the same contract as the definition the instance is pinned to; and when the two definitions use
     * different state classes, the target's must extend the source's. The executor rejects a migration that does not
     * meet these. A matching {@link dev.vertique.workflow.migration.WorkflowMigrationHandler} is keyed by the scope and
     * version of the source and of the target.
     *
     * <p>This default implementation throws {@link UnsupportedOperationException}, as the two-argument form does.
     *
     * @param id workflow instance to migrate
     * @param targetScope the scope of the definition to migrate to; the instance's start scope or the default scope
     * @param targetVersion the definition version to migrate to
     * @return a {@link Future} that completes when the migration is recorded; it fails with
     *     {@link dev.vertique.workflow.migration.WorkflowMigrationIllegalStateException} when the instance has ended
     */
    default Future<Void> migrate(WorkflowInstanceId id, String targetScope, long targetVersion) {
        return Future.failedFuture(
                new UnsupportedOperationException("migrate() is not implemented by this WorkflowOperations binding;"
                        + " install vertique-workflow-postgresql + WorkflowMigrationModule"
                        + " (or another binding that implements migrate)"));
    }
}
